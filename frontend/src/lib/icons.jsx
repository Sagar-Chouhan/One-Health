export function Icon({ name, className = "i", ...rest }) {
  const fullClassName = className ? (className.split(" ").includes("i") ? className : `i ${className}`) : "i";
  return (
    <svg className={fullClassName} {...rest}>
      <use href={`#i-${name}`} />
    </svg>
  );
}
