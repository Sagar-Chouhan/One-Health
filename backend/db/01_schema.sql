SELECT v.village_lgd_code, v.village_name, v.village_type,
       g.gram_panchayat_lgd_code, g.gram_panchayat_name, g.local_body_type,
       b.block_lgd_code, b.block_name,
       d.district_lgd_code, d.district_name, d.division_name,
