CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Per-prefix, per-year running number: next_record_code('VISIT') -> 'VISIT-26-0001'
CREATE TABLE code_sequence (
    prefix      VARCHAR(10) NOT NULL,
    year_2d     SMALLINT    NOT NULL,
    last_value  INTEGER     NOT NULL DEFAULT 0,
    PRIMARY KEY (prefix, year_2d)
);

CREATE OR REPLACE FUNCTION next_record_code(p_prefix TEXT) RETURNS VARCHAR AS $$
DECLARE
    v_year SMALLINT := (EXTRACT(YEAR FROM CURRENT_DATE)::INT % 100);
    v_next INTEGER;
BEGIN
    INSERT INTO code_sequence (prefix, year_2d, last_value)
    VALUES (p_prefix, v_year, 1)
    ON CONFLICT (prefix, year_2d)
    DO UPDATE SET last_value = code_sequence.last_value + 1
    RETURNING last_value INTO v_next;

    RETURN p_prefix || '-' || LPAD(v_year::TEXT, 2, '0') || '-' || LPAD(v_next::TEXT, 4, '0');
END;
$$ LANGUAGE plpgsql;

-- The four COHV types (client instruction, 6 Sep 2026). Stored as the label.
CREATE DOMAIN cohv_type_label AS VARCHAR(20)
    CHECK (VALUE IN ('Public Health', 'Animal', 'Wildlife', 'Environment'));

-- Which surveillance sector a COHV type files under.
CREATE OR REPLACE FUNCTION cohv_type_sector(p_type TEXT) RETURNS VARCHAR AS $$
    SELECT CASE p_type
        WHEN 'Public Health' THEN 'human'
        WHEN 'Animal'        THEN 'animal'
        WHEN 'Wildlife'      THEN 'wildlife'
        WHEN 'Environment'   THEN 'environment'
    END;
$$ LANGUAGE sql IMMUTABLE;


