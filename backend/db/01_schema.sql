FROM village_master v
JOIN gram_panchayat_master g ON g.gram_panchayat_lgd_code = v.gram_panchayat_lgd_code
JOIN block_master          b ON b.block_lgd_code          = v.block_lgd_code
JOIN district_master       d ON d.district_lgd_code       = v.district_lgd_code
JOIN state_master          s ON s.state_lgd_code          = v.state_lgd_code;


-- -----------------------------------------------------------------------------
-- 7. updated_at trigger on every table that has the column
-- -----------------------------------------------------------------------------

DO $$
DECLARE t RECORD;
BEGIN
    FOR t IN
        SELECT c.table_name
        FROM information_schema.columns c
        JOIN information_schema.tables tb
          ON tb.table_name = c.table_name AND tb.table_schema = c.table_schema
        WHERE c.table_schema = 'public' AND c.column_name = 'updated_at'
          AND tb.table_type = 'BASE TABLE'
    LOOP
        EXECUTE format(
            'CREATE TRIGGER trg_%1$s_updated_at BEFORE UPDATE ON %1$I
             FOR EACH ROW EXECUTE FUNCTION set_updated_at()', t.table_name);
    END LOOP;
END;
$$;

