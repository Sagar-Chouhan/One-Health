-- Tokens revoked on logout. Access tokens are stateless JWTs, so logout works
-- by listing the token's jti here; the API refuses any token whose jti is
-- present. A row is only needed until the token would expire on its own
-- (expires_at), after which it is purged.
CREATE TABLE revoked_token (
    jti          VARCHAR(64)  PRIMARY KEY,
    volunteer_id BIGINT       NOT NULL REFERENCES volunteer_registration (volunteer_id) ON DELETE CASCADE,
    expires_at   TIMESTAMPTZ  NOT NULL,
    revoked_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_revoked_token_expires ON revoked_token (expires_at);

