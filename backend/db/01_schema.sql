    supervisor_id            INTEGER      REFERENCES cohv_supervisor (supervisor_id),

    pin_hash                 VARCHAR(255) NOT NULL,           -- hash of the 4-6 digit PIN, never plain
    photo_path               VARCHAR(500),

    -- Section S: supervisor approves / activates.
    status                   VARCHAR(20)  NOT NULL DEFAULT 'PENDING'
