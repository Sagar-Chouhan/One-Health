-- =============================================================================
-- OneHealth COHV Reporting - PostgreSQL schema (v2)
--
-- Built from cohv-app_prototype.html. Run on an EMPTY database:
--     psql -U postgres -d onehealth_v2 -f 01_schema.sql
--     psql -U postgres -d onehealth_v2 -f 02_seed_masters.sql
--
-- Key decisions
--   * Location masters use the LGD code itself as the PRIMARY KEY, so every
--     foreign key in the system points at an LGD code - never a local serial id.
--   * Each lower level also carries its ancestors' LGD codes, tied together by a
--     composite FK, so a village can never be filed under the wrong block/district.
--   * Record codes (COHV-26-0001, VISIT-26-0001, ...) are generated by the
--     database (next_record_code), so two API workers can never hand out the same one.
--   * Offline sync: every field record carries client_ref (the id the device gave
--     it) with UNIQUE (volunteer_id, client_ref) - re-uploading the same record
--     is a no-op instead of a duplicate (prototype section R).
--   * Fixed vocabularies (statuses, risk levels, stages, COHV type) are CHECK
--     constraints; lists an admin may edit are master tables.
--   * COHV type is stored as its label, exactly as the app shows it:
--     'Public Health' | 'Animal' | 'Wildlife' | 'Environment'. There is no
--     master table for it; its sector mapping lives in cohv_type_sector().
-- =============================================================================

